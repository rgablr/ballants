#!/usr/bin/env python3
"""Generates levels/nest/level_4_worker_rush.tscn (the scene only; the bot
drive files in tests/levels/level_4_worker_rush*.json are hand-tuned).

    python3 tools/make_worker_rush.py      (run from ballants-game/)

Everything is flat at floor height Y (4 m), built from right angles so the
crossings, side tunnels and worker paths line up by construction:

  S1  single line     x = 0, z  6 .. -62   (heading -Z)   one line crosses at z = -30
      bend left       radius 20 to heading -X
  S2  crossing lines  z = -82, x -20 .. -80                two lanes cross at x = -43 / -47;
                      the +Z side tunnel is long and bends to hidden crystal 1
      bend right      radius 20 to heading -Z
  S3  crumb highway   x = -100, z -102 .. -199             two lanes along it, crumb piles
  S4  storage gate    z -199 .. -226 approach, gate at z = -226.5, chamber to -252

"left"/"right" are as seen rolling along the course.
"""
import math
import os

Y = 4.0
W1 = 9.0      # corridor widths
W3 = 10.0
CH = 22.0     # storage chamber width
TUN_CEIL = 3.2
OVER = 0.3    # side tunnels start this far inside the corridor floor


def fmt(v):
    v = round(v, 3)
    if v == int(v):
        return str(int(v))
    return ("%.3f" % v).rstrip("0").rstrip(".")


def v3(p):
    return "Vector3(%s, %s, %s)" % tuple(fmt(c) for c in p)


def vec3_array(pts):
    return "PackedVector3Array(" + ", ".join(", ".join(fmt(c) for c in p) for p in pts) + ")"


def f32_array(vals):
    return "PackedFloat32Array(" + ", ".join(fmt(v) for v in vals) + ")"


def i32_array(vals):
    return "PackedInt32Array(" + ", ".join(str(v) for v in vals) + ")"


def offset_path(pts, amount):
    """Offsets a polyline to the LEFT (seen walking it) by `amount` m."""
    out = []
    n = len(pts)
    for i, p in enumerate(pts):
        a = pts[max(i - 1, 0)]
        b = pts[min(i + 1, n - 1)]
        dx, dz = b[0] - a[0], b[2] - a[2]
        L = math.hypot(dx, dz)
        dx, dz = dx / L, dz / L
        # right = (-dz, dx); left = (dz, -dx)
        out.append((p[0] + dz * amount, p[1], p[2] - dx * amount))
    return out


def arc(center, radius, a0, a1, step=5.0, fn=None):
    pts = []
    n = max(int(math.ceil(abs(a1 - a0) / step)), 1)
    for k in range(1, n + 1):
        a = math.radians(a0 + (a1 - a0) * k / n)
        pts.append(fn(center, radius, a))
    return pts


def densify(pts, widths, walls, step):
    """Splits long segments so neighbouring segments are similar lengths:
    a Catmull-Rom curve through unevenly spaced points overshoots and folds
    the floor (a short segment next to a long one made a bump)."""
    P, Wd, C = [pts[0]], [widths[0]], [walls[0]]
    for i in range(1, len(pts)):
        a, b = pts[i - 1], pts[i]
        n = max(int(math.ceil(math.dist(a, b) / step)), 1)
        for k in range(1, n + 1):
            u = k / n
            P.append(tuple(a[j] + (b[j] - a[j]) * u for j in range(3)))
            Wd.append(widths[i - 1] + (widths[i] - widths[i - 1]) * u if k < n else widths[i])
            C.append(walls[i - 1] if k < n else walls[i])
    return P, Wd, C


class Scene:
    def __init__(self):
        self.ext = []
        self.nodes = []

    def res(self, kind, path):
        rid = "%d_r" % (len(self.ext) + 1)
        self.ext.append('[ext_resource type="%s" path="%s" id="%s"]' % (kind, path, rid))
        return rid

    def node(self, text):
        self.nodes.append(text)

    def write(self, path, header):
        out = ["[gd_scene format=3]", ""] + self.ext + [""] + header + [""] + self.nodes
        with open(path, "w") as f:
            f.write("\n".join(out) + "\n")


def main():
    s = Scene()
    R_LEVEL = s.res("Script", "res://levels/level.gd")
    R_THEME = s.res("PackedScene", "res://levels/nest/anthill_theme.tscn")
    R_START = s.res("PackedScene", "res://src/objects/start_point.tscn")
    R_HILL = s.res("PackedScene", "res://src/objects/ant_hill.tscn")
    R_FALL = s.res("PackedScene", "res://src/objects/fall_zone.tscn")
    R_TRACK = s.res("Script", "res://src/objects/nest/dirt_track.gd")
    R_WALL = s.res("Script", "res://src/objects/nest/dirt_wall.gd")
    R_CRYSTAL = s.res("PackedScene", "res://src/objects/hidden_crystal.tscn")
    R_FUNGUS = s.res("Script", "res://src/objects/nest/glow_fungus.gd")
    R_LINE = s.res("Script", "res://src/objects/nest/worker_line.gd")
    R_GATE = s.res("Script", "res://src/objects/nest/storage_gate.gd")
    R_PILE = s.res("Script", "res://src/objects/nest/crumb_pile.gd")
    R_WCRYSTAL = s.res("Script", "res://src/objects/nest/wall_crystal.gd")

    header = [
        "; LEVEL 4 -- Worker Rush. GENERATED by tools/make_worker_rush.py: edit",
        "; that and re-run it rather than moving things here by hand.",
        '[node name="Level4WorkerRush" type="Node3D"]',
        'script = ExtResource("%s")' % R_LEVEL,
        'level_name = "Worker Rush"',
        "",
        '[node name="AnthillTheme" parent="." instance=ExtResource("%s")]' % R_THEME,
        "",
        '[node name="StartPoint" parent="." instance=ExtResource("%s")]' % R_START,
        "position = %s" % v3((0, Y, 0)),
    ]

    # ------------------------------------------------------- main track
    pts, widths, walls = [], [], []

    def add(p, w, code):
        pts.append((p[0], Y, p[1]))
        widths.append(w)
        walls.append(code)

    # S1: heading -Z. Crossing gap both sides z -27 .. -33.
    for z, code in [(6, 3), (0, 3), (-10, 3), (-20, 3), (-27, 0), (-33, 3), (-42, 3), (-52, 3), (-62, 3)]:
        add((0, z), W1, code)
    # Bend left, center (-20, -62).
    for p in arc((-20, -62), 20, 0, 90, fn=lambda c, r, a: (c[0] + r * math.cos(a), c[1] - r * math.sin(a))):
        add(p, W1, 3)
    # S2: heading -X. Crossing gap both sides x -41.5 .. -48.5.
    for x, code in [(-26, 3), (-34, 3), (-41.5, 0), (-48.5, 3), (-56, 3), (-64, 3), (-72, 3), (-80, 3)]:
        add((x, -82), W1, code)
    # Bend right, center (-80, -102).
    bend2 = arc((-80, -102), 20, 0, 90, fn=lambda c, r, a: (c[0] - r * math.sin(a), c[1] + r * math.cos(a)))
    for i, p in enumerate(bend2):
        add(p, W1 if i < len(bend2) - 1 else W3, 3)
    # S3: the highway, heading -Z. Tunnel gaps both sides at z -105..-109 and -195..-199.
    for z, code in [(-105, 0), (-109, 3), (-118, 3), (-128, 3), (-138, 3), (-148, 3), (-158, 3),
                    (-168, 3), (-178, 3), (-188, 3), (-195, 0), (-199, 3)]:
        add((-100, z), W3, code)
    # S4: approach (gate tunnel gap on the left at z -210..-214), the gate, the chamber.
    for z, w, code in [(-203, W1, 3), (-210, W1, 2), (-214, W1, 3), (-220, W1, 3), (-226, W1, 0),
                       (-227, CH, 3), (-235, CH, 3), (-243, CH, 3), (-252, CH, 3)]:
        add((-100, z), w, code)

    pts, widths, walls = densify(pts, widths, walls, 2.0)
    s.node('[node name="Track" type="StaticBody3D" parent="."]')
    s.node('script = ExtResource("%s")' % R_TRACK)
    s.node("points = " + vec3_array(pts))
    s.node("widths = " + f32_array(widths))
    s.node("walls = " + i32_array(walls))
    s.node("wall_height = 3.0")
    s.node("lights_every = 12.0")
    s.node("seed = 41\n")

    # Back wall of the chamber.
    wall(s, R_WALL, "ChamberBack", (-100, -252.5), 90, CH + 2, 3.5, 1.0, 7)

    # ------------------------------------------------------ side tunnels
    tunnels = []   # (name, points, width)

    def tunnel(name, start, direction, length, width, cap=True, seed=1, extra=None):
        dx, dz = direction
        p0 = (start[0] - dx * OVER, Y, start[1] - dz * OVER)
        p1 = (start[0] + dx * 0.7, Y, start[1] + dz * 0.7)
        tp = [p0, p1]
        if extra is None:
            tp.append((start[0] + dx * length, Y, start[1] + dz * length))
        else:
            tp += extra
        tp, _, codes = densify(tp, [width] * len(tp), [0] + [3] * (len(tp) - 1), 1.2)
        s.node('[node name="%s" type="StaticBody3D" parent="."]' % name)
        s.node('script = ExtResource("%s")' % R_TRACK)
        s.node("points = " + vec3_array(tp))
        s.node("width = %s" % fmt(width))
        s.node("walls = " + i32_array(codes))
        s.node("wall_height = %s" % fmt(TUN_CEIL))
        s.node("ceiling_height = %s" % fmt(TUN_CEIL))
        s.node("floor_thickness = 0.8")
        s.node("lights_every = 9.0")
        s.node("samples_per_meter = 1.5")
        s.node("seed = %d\n" % seed)
        if cap:
            end = tp[-1]
            a, b = tp[-2], tp[-1]
            ex, ez = b[0] - a[0], b[2] - a[2]
            L = math.hypot(ex, ez)
            ex, ez = ex / L, ez / L
            yaw = 90 if abs(ex) < 0.5 else 0
            wall(s, R_WALL, name + "Cap", (end[0] + ex * 0.5, end[2] + ez * 0.5), yaw, width + 1.6, TUN_CEIL + 0.4, 1.0, seed + 3)
        tunnels.append((name, tp, width))
        return tp

    # S1: one line from left to right across z = -30.
    tunnel("S1TunnelLeft", (-W1 / 2, -30), (-1, 0), 12 - W1 / 2, 8.5, seed=3)
    tunnel("S1TunnelRight", (W1 / 2, -30), (1, 0), 12 - W1 / 2, 8.5, seed=5)

    # S2: the long tunnel on the +Z side (left as you roll -X) and a short
    # dead end opposite. Centerline at x = -45.
    long_extra = [(-45, Y, -66)]
    long_extra += [(p[0], Y, p[1]) for p in arc((-53, -66), 8, 0, 90, step=7.5,
                                                 fn=lambda c, r, a: (c[0] + r * math.cos(a), c[1] + r * math.sin(a)))]
    long_extra += [(-63.4, Y, -58)]
    long_pts = tunnel("S2LongTunnel", (-45, -82 + W1 / 2), (0, 1), 0, 9.5, seed=7, extra=long_extra)
    short_pts = tunnel("S2ShortTunnel", (-45, -82 - W1 / 2), (0, -1), 95 - 82 - W1 / 2, 9.5, seed=9)

    # S3: four short tunnels at the highway's ends.
    for nm, x0, dx, z in [("S3StartLeft", -100 - W3 / 2, -1, -107), ("S3StartRight", -100 + W3 / 2, 1, -107),
                          ("S3EndLeft", -100 - W3 / 2, -1, -197), ("S3EndRight", -100 + W3 / 2, 1, -197)]:
        tunnel(nm, (x0, z), (dx, 0), 12.5 - W3 / 2, 6.5, seed=11 + len(tunnels))
    # S4: the gate line's tunnel on the left.
    tunnel("S4GateTunnel", (-100 - W1 / 2, -212), (-1, 0), 11.5 - W1 / 2, 6.5, seed=31)

    # ----------------------------------------------------- worker lines
    def line(name, path, key, extra_lines=(), hidden=4.0, seed=1):
        s.node('[node name="%s" type="Node3D" parent="."]' % name)
        s.node('script = ExtResource("%s")' % R_LINE)
        s.node("points = " + vec3_array(path))
        s.node("hidden_length = %s" % fmt(hidden))
        s.node('speed_key = "worker_rush_%s_speed"' % key)
        if key != "gate":
            s.node('spacing_key = "worker_rush_%s_spacing"' % key)
        for l in extra_lines:
            s.node(l)
        s.node("seed = %d\n" % seed)

    # S1: left to right, 1 m inside each cap.
    line("SingleLine", [(-13, Y, -30), (13, Y, -30)], "single", ["offset = 1.0"], seed=2)

    # S2: lane A walks out of the long tunnel (its left side) and across to
    # the short tunnel; lane B the other way on the other side.
    centre = long_pts[1:]                    # corridor edge .. tunnel end
    centre = [(-45, Y, -82 + W1 / 2)] + centre
    lane_a_long = offset_path(centre, 2.0)   # x = -43 at the corridor
    lane_b_long = offset_path(centre, -2.0)  # x = -47
    end_x = long_pts[-1][0] - 1.0            # 1 m past the cap face
    lane_a_long[-1] = (end_x, Y, lane_a_long[-1][2])
    lane_b_long[-1] = (end_x, Y, lane_b_long[-1][2])
    short_end = short_pts[-1][2] - 1.0       # cap face at short_pts[-1], 1 m in
    lane_a = list(reversed(lane_a_long)) + [(-43, Y, short_end)]
    lane_b = [(-47, Y, short_end)] + lane_b_long
    line("CrossLaneA", lane_a, "cross_a", ["offset = 0.0"], seed=4)
    line("CrossLaneB", lane_b, "cross_b", ["offset = 0.75"], seed=6)

    # S3: the oncoming lane on the left (x = -102, walking +Z) and the lane
    # going your way on the right (x = -98, walking -Z) with the carrier.
    on = [(-113.5, Y, -197), (-105, Y, -197), (-102, Y, -194), (-102, Y, -110), (-105, Y, -107), (-113.5, Y, -107)]
    wth = [(-86.5, Y, -107), (-95, Y, -107), (-98, Y, -110), (-98, Y, -194), (-95, Y, -197), (-86.5, Y, -197)]
    line("HighwayOncoming", on, "highway_on", ["offset = 3.0"], seed=8)
    line("HighwayWith", wth, "highway_with", ["offset = 5.0", "crystal_carrier = 0", "crystal_which = 0"], seed=10)

    # S4: out of the gate tunnel, through the left half of the doorway, into
    # the chamber and off into a hole in its left wall.
    gate_z = -226.5
    gl = [(-112.5, Y, -212), (-104, Y, -212), (-101, Y, -215), (-101, Y, -231), (-104, Y, -234), (-112, Y, -234)]
    d_door = math.dist(gl[0], gl[1]) + math.dist(gl[1], gl[2]) + (-215 - gate_z)
    line("GateLine", gl, "gate", ['sync_gate = NodePath("../StorageGate")', "sync_distance = %s" % fmt(d_door)], seed=12)

    # ---------------------------------------------------- crumb highway
    for i, (x, z, sx) in enumerate([(-100, -124, 2.6), (-104.15, -142, 2.9), (-95.85, -142, 2.9),
                                    (-100, -160, 2.6), (-104.15, -178, 2.9), (-95.85, -178, 2.9)]):
        s.node('[node name="CrumbPile%d" type="StaticBody3D" parent="."]' % (i + 1))
        s.node('script = ExtResource("%s")' % R_PILE)
        s.node("position = %s" % v3((x, Y, z)))
        s.node("size = Vector3(%s, 1.4, 3)" % fmt(sx))
        s.node("seed = %d\n" % (i * 7 + 3))

    # ------------------------------------------------------- the gate
    s.node('[node name="StorageGate" type="Node3D" parent="."]')
    s.node('script = ExtResource("%s")' % R_GATE)
    s.node("position = %s" % v3((-100, Y, gate_z)))
    s.node("width = 4.0")
    s.node("height = 3.0\n")
    wall(s, R_WALL, "GateWallLeft", (-107, gate_z), 90, 10, 3.5, 1.0, 13)
    wall(s, R_WALL, "GateWallRight", (-93, gate_z), 90, 10, 3.5, 1.0, 17)

    # ------------------------------------------------- hidden crystals
    s.node('[node name="TunnelCrystal" parent="." instance=ExtResource("%s")]' % R_CRYSTAL)
    s.node("position = %s" % v3((-61.2, Y, -58)))
    s.node("which = 1\n")
    fungus(s, R_FUNGUS, "TunnelCrystalGlow", (-62.6, Y, -55.3), False, 1.6, 0.9)
    fungus(s, R_FUNGUS, "TunnelBendGlow", (-49.6, Y, -60.0), False, 1.0, 0.8)

    # Landmarks: an amber crystal cluster beside each section's start.
    for name, p, seed in [("MarkSingle", (3.6, Y, -22), 2), ("MarkCross", (-37, Y, -85.6), 4),
                          ("MarkHighway", (-95.6, Y, -114), 6), ("MarkGate", (-95.4, Y, -205), 8)]:
        s.node('[node name="%s" type="Node3D" parent="."]' % name)
        s.node('script = ExtResource("%s")' % R_WCRYSTAL)
        s.node("position = %s" % v3(p))
        s.node("seed = %d\n" % seed)

    # Goal.
    fungus(s, R_FUNGUS, "GoalGlowLeft", (-108.5, Y, -247), True, 1.6, 1.0)
    fungus(s, R_FUNGUS, "GoalGlowRight", (-91.5, Y, -247), True, 1.6, 1.0)
    s.node('[node name="AntHill" parent="." instance=ExtResource("%s")]' % R_HILL)
    s.node("position = %s" % v3((-100, Y, -243)))
    s.node("base_radius = 5.0\n")
    s.node('[node name="FallZone" parent="." instance=ExtResource("%s")]' % R_FALL)
    s.node("position = Vector3(-50, -1, -120)")
    s.node("size = Vector3(600, 4, 600)")

    out = os.path.join(os.path.dirname(__file__), "..", "levels", "nest", "level_4_worker_rush.tscn")
    s.write(out, header)
    total = sum(math.dist(pts[i - 1], pts[i]) for i in range(1, len(pts)))
    print("main track: %d points, %.0f m of centerline" % (len(pts), total))
    print("gate line: door at %.2f m along its path" % d_door)
    for nm, tp, w in tunnels:
        print("  %-14s %s .. %s" % (nm, tp[0], tp[-1]))


def wall(s, r, name, at, yaw, length, height, thickness, seed):
    s.node('[node name="%s" type="StaticBody3D" parent="."]' % name)
    s.node('script = ExtResource("%s")' % r)
    s.node("position = %s" % v3((at[0], Y, at[1])))
    if yaw:
        s.node("rotation_degrees = Vector3(0, %s, 0)" % fmt(yaw))
    s.node("length = %s" % fmt(length))
    s.node("height = %s" % fmt(height))
    s.node("thickness = %s" % fmt(thickness))
    s.node("seed = %d\n" % seed)


def fungus(s, r, name, p, amber, size, energy):
    s.node('[node name="%s" type="Node3D" parent="."]' % name)
    s.node('script = ExtResource("%s")' % r)
    s.node("position = %s" % v3(p))
    s.node("amber = %s" % ("true" if amber else "false"))
    s.node("size = %s" % fmt(size))
    s.node("light_energy = %s\n" % fmt(energy * 1.5))


if __name__ == "__main__":
    main()
